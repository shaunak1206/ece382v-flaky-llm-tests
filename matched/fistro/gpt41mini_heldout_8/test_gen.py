import pytest
import json
from dataclasses import dataclass, field, fields, is_dataclass

from fistro.fistro import generate, enrich_fields, generate_from_json, inner_inspection, get_class_body_from_annotations
from fistro.generators import int_generator


@dataclass
class Sample:
    x: int
    y: str = "default"
    z: float = field(default=1.23)


@dataclass
class NestedSample:
    a: int
    b: dict
    c: list


def test_generate_returns_dataclass():
    result = generate(Sample)
    assert is_dataclass(result)
    assert result.__name__ == "Sample"


def test_generate_instance_defaults_generated():
    GeneratedClass = generate(Sample)
    instance = GeneratedClass()
    # x is int generated by Factory, so it should be int
    assert isinstance(instance.x, int)
    # y has default "default"
    assert instance.y == "default"
    assert isinstance(instance.z, float)
    assert instance.z == 1.23


def test_generate_as_dict_returns_dict():
    result = generate(Sample, as_dict=True)
    assert isinstance(result, dict)
    assert "x" in result
    assert "y" in result
    assert "z" in result


def test_generate_as_json_returns_valid_json():
    result = generate(Sample, as_json=True)
    assert isinstance(result, str)
    loaded = json.loads(result)
    assert "x" in loaded
    assert "y" in loaded
    assert "z" in loaded


def test_enrich_fields_without_generators_uses_default_factory():
    result = enrich_fields(Sample, generators=None)
    # Should have same number of results as Sample fields
    assert len(result) == len(fields(Sample))
    for field_tuple in result:
        # Each tuple: (name, type, field)
        assert isinstance(field_tuple, tuple)
        assert len(field_tuple) == 3


def test_enrich_fields_with_generators_uses_given_generators():
    dummy_gen = [lambda t: lambda: 42]
    result = enrich_fields(Sample, dummy_gen)
    for _, _, f in result:
        # The default_factory should be a callable that returns 42
        if f.default_factory is not None:
            assert f.default_factory() == 42


def test_generate_from_json_creates_dataclass():
    data = {"field1": 123, "field2": "abc"}
    cls = generate_from_json(data)
    # Should be a dataclass type (not instance)
    assert is_dataclass(cls)
    # It should have fields matching data keys
    cls_fields = {f.name for f in fields(cls)}
    assert set(data.keys()) == cls_fields
    # Each field type is as returned by inner_inspection: should be a type
    for f in fields(cls):
        assert hasattr(f.type, "__origin__") or isinstance(f.type, type)


def test_generate_from_json_raises_for_list():
    with pytest.raises(NotImplementedError):
        generate_from_json([1, 2, 3])


@pytest.mark.parametrize("value,expected_type", [
    ({"k": 1}, dict),
    ([1, 2, 3], list),
    (42, int),
    ("abc", str),
])
def test_inner_inspection_types(value, expected_type):
    type_, f = inner_inspection(value)
    if expected_type is dict:
        # type_ should be typing.Dict with key and value types
        assert type_.__origin__ == dict
    elif expected_type is list:
        assert type_.__origin__ == list
    else:
        assert type_ == expected_type
    # field default_factory returns value
    assert f.default_factory() == value


