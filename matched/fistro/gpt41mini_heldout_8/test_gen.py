def test_generate_field_defaults_are_used_when_present():
    @dataclass
    class Defaults:
        x: int = 10
        y: str = "fixed"

    cls = generate(Defaults)
    instance = cls()
    assert instance.x == 10
    assert instance.y == "fixed"


def test_inner_inspection_field_factory_allows_mutable_defaults():
    list_value = [1, 2, 3]
    t, f = inner_inspection(list_value)
    # Each new call returns a fresh list equal to list_value
    v1 = f.default_factory()
    v2 = f.default_factory()
    assert v1 == list_value
    assert v2 == list_value
    assert v1 is not v2  # different instances


def test_generate_from_json_handles_nested_dict():
    data = {"outer": {"inner": 5}}
    cls = generate_from_json(data)
    instance = cls()
    # outer field is Dict with key and value types
    outer_field = next(f for f in fields(cls) if f.name == "outer")
    assert outer_field.type.__origin__ == dict
    val = getattr(instance, "outer")
    assert isinstance(val, dict)
    # default_factory returns same dict value
    assert val == {"inner": 5}
