def test_generate_returns_dataclass_type_when_no_flags():
    generated_cls = generate(Simple)
    assert callable(generated_cls)
    # It should behave as a dataclass
    instance = generated_cls()
    # Should have the correct fields with proper types
    for f_orig, f_gen in zip(fields(Simple), fields(generated_cls)):
        assert f_orig.name == f_gen.name
        assert f_orig.type == f_gen.type
    # Defaults should be preserved
    assert instance.y == "default"
    assert instance.z is True


