@pytest.mark.parametrize(
    "value,expected_type_check",
    [
        ({"k": 1, "k2": 2}, lambda t: str(t).startswith("typing.Dict")),
        ([1, 2, 3], lambda t: str(t).startswith("typing.List")),
        ([1, "a"], lambda t: str(t).startswith("typing.List")),
        (42, lambda t: t == int),
        ("hello", lambda t: t == str),
    ],
)
def test_inner_inspection_returns_expected_type(value, expected_type_check):
    t, f = inner_inspection(value)
    # default_factory returns the original value instance (and new when called)
    v = f.default_factory()
    # Check type via callback predicate (cannot rely on direct equality for generics)
    assert expected_type_check(t)
    # The factory returns an equal value but distinct object when mutable
    if isinstance(value, (dict, list)):
        assert v == value
        # For mutable types the factory produces a new instance on call, thus not "is"
        # Default factory produces new lambda each time so different instances
        v2 = f.default_factory()
        assert v is not v2
        assert v2 == v
    else:
        assert v == value


def test_get_class_body_from_annotations_various_types():
    from typing import Dict, List, Any

    annotations = {
        "a": int,
        "b": Dict[str, int],
        "c": List[int],
        "d": None,
        "e": Any,
    }
    result = get_class_body_from_annotations(annotations)
    # It should include type names or typing types as string
    assert "a: int" in result
    assert "b: typing.Dict" in result or "b: Dict" in result
    assert "c: typing.List" in result or "c: List" in result
    # For None type key should output "d: Any"
    assert "d: Any" in result


