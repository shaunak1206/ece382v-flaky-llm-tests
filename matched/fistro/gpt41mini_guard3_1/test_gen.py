def test_enrich_fields_with_and_without_generators():
    # Without generators, Factory().factory used
    fields_default = enrich_fields(Simple, None)
    # With provided dummy generators list, Factory initialized with that
    dummy_gen = [lambda t: lambda: 123]
    fields_custom = enrich_fields(Simple, dummy_gen)
    # Both produce list of tuples of same length
    assert len(fields_default) == len(fields_custom) == len(fields(Simple))

    # Each element is (name, type, field)
    for fd, fc in zip(fields_default, fields_custom):
        assert fd[0] == fc[0]
        assert fd[1] == fc[1]
        # The fields should have default or default_factory set, check callables for default_factory
        assert (fd[2].default is MISSING) != (fd[2].default_factory is not None)
        assert (fc[2].default is MISSING) != (fc[2].default_factory is not None)


def test_generate_from_json_creates_dataclass_with_fields():
    obj = {"foo": 123, "bar": "baz", "nested": {"a": 1, "b": 2}}

    dc = generate_from_json(obj)
    # The returned object is a dataclass type
    assert callable(dc)
    dc_fields = fields(dc)
    # All keys used as field names
    assert set(f.name for f in dc_fields) == set(obj.keys())
    # Field types are inspected correctly
    # "foo" is int
    foo_field = next(f for f in dc_fields if f.name == "foo")
    assert foo_field.type is int
    # "bar" is str
    bar_field = next(f for f in dc_fields if f.name == "bar")
    assert bar_field.type is str
    # "nested" is a Dict field (because inner_inspection picks the first key, value types)
    nested_field = next(f for f in dc_fields if f.name == "nested")
    # Cannot rely on exact generic type due to typing implementation details,
    # but should be typing.Dict containing key and value types
    # We check type annotations for Dict[X, Y]
    type_str = str(nested_field.type)
    assert 'Dict' in type_str  # basic check


