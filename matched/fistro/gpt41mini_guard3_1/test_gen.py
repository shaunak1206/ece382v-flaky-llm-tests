def test_inner_inspection_factory_returns_distinct_values_each_call():
    value = {"key": "val"}
    typ, f = inner_inspection(value)
    val1 = f.default_factory()
    val2 = f.default_factory()
    # Both are equal to original value, but distinct objects (new dicts)
    assert val1 == value
    assert val2 == value
    assert val1 is not val2


def test_generate_as_dict_and_as_json_consistency():
    generated_dict = generate(Simple, as_dict=True)
    generated_json = generate(Simple, as_json=True)
    import json

    loaded = json.loads(generated_json)
    # Both must produce consistent data keys and types
    assert set(generated_dict.keys()) == set(loaded.keys())
    for k in generated_dict.keys():
        v_dict = generated_dict[k]
        v_json = loaded[k]
        if isinstance(v_dict, float):
            assert abs(v_dict - v_json) < 1e-9
        else:
            assert v_dict == v_json


