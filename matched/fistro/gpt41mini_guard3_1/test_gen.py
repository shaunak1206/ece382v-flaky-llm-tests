def test_generate_with_custom_generators(monkeypatch):
    # Patch Factory.factory method to return a constant factory for int type only
    created_call_args = []

    def fake_factory(self, t):
        created_call_args.append(t)
        if t is int:
            return lambda: 42
        # fallback
        return lambda: None

    from fistro.fistro import Factory

    monkeypatch.setattr(Factory, "factory", fake_factory)

    @dataclass
    class TestClass:
        a: int
        b: str

    generated_cls = generate(TestClass, generators=[int_generator])
    instance = generated_cls()
    # The int field 'a' should use the fake factory and return 42
    assert instance.a == 42
    # b is str type and factory returns None per fallback
    assert instance.b is None
    # The factory factory method was called with int and str types
    assert int in created_call_args
    assert str in created_call_args


